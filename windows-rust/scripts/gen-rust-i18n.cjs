#!/usr/bin/env node
/**
 * Generates src/i18n_table.rs from the renderer dictionary at
 * web/shared/i18n.js — the byte-for-byte copy of the Electron renderer's
 * i18n.js, which is the source of truth now that the Electron tree lives only
 * in git history.
 *
 *   node scripts/gen-rust-i18n.cjs
 *
 * i18n.js only exports { EN, JA } — EN_ONE is internal to t() — so the source is
 * re-compiled once with EN_ONE added to the export list. That keeps the Rust
 * tray/dialog/notification strings byte-identical to the renderer's without
 * hand-copying 300 sentences.
 */
'use strict';

const path = require('path');
const fs = require('fs');
const Module = require('module');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.resolve(ROOT, 'web', 'shared', 'i18n.js');
const OUT = path.join(ROOT, 'src', 'i18n_table.rs');

const source = fs.readFileSync(SRC, 'utf8');
const patched = source.replace('return { t,', 'return { EN_ONE, t,');
if (patched === source) {
  // export list changed upstream
  const m = source.match(/return \{ t, [^}]*\}/);
  throw new Error(`could not patch i18n.js export list${m ? `: ${m[0]}` : ''}`);
}
const mod = new Module(SRC, module);
mod.filename = SRC;
mod.paths = Module._nodeModulePaths(path.dirname(SRC));
mod._compile(patched, SRC);
const i18n = mod.exports;

/** Rust string literal escaping; keep UTF-8 text readable. */
function lit(value) {
  let out = '"';
  for (const ch of String(value)) {
    const code = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return out + '"';
}

function table(name, dict) {
  const rows = Object.entries(dict).map(([k, v]) => {
    if (typeof v !== 'string') throw new Error(`${name}["${k}"] is not a string (${typeof v})`);
    return `    (${lit(k)}, ${lit(v)}),`;
  });
  return `pub static ${name}: &[(&str, &str)] = &[\n${rows.join('\n')}\n];\n`;
}

const readme = `// @generated by scripts/gen-rust-i18n.cjs from web/shared/i18n.js
// Do not edit by hand. Re-run the generator after changing the dictionary.

`;

const one = Object.entries(i18n.EN_ONE || {}).map(([k, v]) => {
  if (typeof v === 'string') return `    (${lit(k)}, OneSpec::Text(${lit(v)})),`;
  if (typeof v === 'function') return `    (${lit(k)}, OneSpec::Fn),`;
  throw new Error(`unsupported EN_ONE entry: ${k}`);
});

const body = [
  readme,
  table('EN', i18n.EN),
  table('JA', i18n.JA || {}),
  `/// English singular variant of a sentence; \`Fn\` entries are implemented by\n/// \`one_fn\` in i18n.rs (they carry two independent counts).\npub enum OneSpec {\n    Text(&'static str),\n    Fn,\n}\n`,
  `pub static EN_ONE: &[(&str, OneSpec)] = &[\n${one.join('\n')}\n];\n`,
].join('\n');

fs.writeFileSync(OUT, body, 'utf8');
console.log(`[i18n] wrote ${path.relative(ROOT, OUT)}: EN=${Object.keys(i18n.EN).length} JA=${Object.keys(i18n.JA || {}).length} EN_ONE=${Object.keys(i18n.EN_ONE || {}).length}`);
